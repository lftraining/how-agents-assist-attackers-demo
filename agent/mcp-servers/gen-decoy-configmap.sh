#!/usr/bin/env bash
#
# gen-decoy-configmap.sh — regenerate the decoy ConfigMap manifest from
# attacker/decoy-creds/credentials. Re-run it whenever the decoy changes.
set -euo pipefail

# shellcheck source=../../scripts/lib/common.sh
source "$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)/scripts/lib/common.sh"

SRC="${REPO_ROOT}/attacker/decoy-creds/credentials"
OUT="${REPO_ROOT}/agent/mcp-servers/k8s/00-mcp-fs-decoy-configmap.yaml"
# The file name the decoy gets inside the pod.
KEY="credentials"

[ -f "$SRC" ] || { echo "FATAL decoy source not found: $SRC (it is the decoy's single source)" >&2; exit 1; }

# Build the manifest with kubectl, so the encoding is always valid, then add the labels.
kc -n "$DEMO_NS" create configmap mcp-fs-decoy \
  --from-file="${KEY}=${SRC}" \
  --dry-run=client -o yaml \
| kc label --local -f - -o yaml \
    app="$MCP_FS_DEPLOY" "${ROLE_LABEL_KEY}=${ROLE_FS}" \
> "${OUT}.tmp"

{
  echo "# 00-mcp-fs-decoy-configmap.yaml — GENERATED by agent/mcp-servers/gen-decoy-configmap.sh."
  echo "# Source: attacker/decoy-creds/credentials. Do not edit by hand; re-run the generator if"
  echo "# the decoy changes."
  cat "${OUT}.tmp"
} > "$OUT"
rm -f "${OUT}.tmp"
echo "wrote $OUT from $SRC"
